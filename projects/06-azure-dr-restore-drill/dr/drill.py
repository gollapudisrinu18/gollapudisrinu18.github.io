#!/usr/bin/env python3
"""Repeatable backup-and-restore drill with RTO/RPO measurement.

Timeline (synthetic clock for RPO, wall clock for restore):
  T-45 min  scheduled backup completes
  T-45..0   new orders keep arriving (not yet in any backup)
  T 0       accidental deletion of the primary dataset
  detect -> restore latest backup -> verify checksums -> report

Writes docs/drill-report.md.
"""
import argparse
import json
import os
import shutil
import sys
import tempfile
from datetime import datetime, timedelta, timezone

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import drlib  # noqa: E402

DETECTION_MINUTES = 4   # time for the deletion alert to page (modelled, from the alert rule)
DECISION_MINUTES = 3    # incident commander approves the restore (modelled)
LATE_RECORDS = 37
MINUTES_SINCE_BACKUP = 45


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--report", default=os.path.join(HERE, "..", "docs", "drill-report.md"))
    ap.add_argument("--workdir")
    args = ap.parse_args(argv)
    cfg = json.load(open(os.path.join(HERE, "config.json")))

    work = args.workdir or tempfile.mkdtemp(prefix="dr-drill-")
    primary, vault = os.path.join(work, "primary"), os.path.join(work, "vault")
    os.makedirs(vault, exist_ok=True)
    incident_at = datetime.now(timezone.utc).replace(microsecond=0)
    backup_at = incident_at - timedelta(minutes=MINUTES_SINCE_BACKUP)

    print("=== 1. Prepare synthetic dataset and scheduled backup ===")
    drlib.generate_dataset(primary, cfg["dataset_files"], cfg["records_per_file"])
    snap, manifest = drlib.take_backup(primary, vault, when=backup_at)
    print(f"  backup {os.path.basename(snap)}: {len(manifest['files'])} files, {manifest['records']} records")
    drlib.append_records(primary, LATE_RECORDS)
    before = drlib.count_records(primary)
    print(f"  {LATE_RECORDS} orders written in the {MINUTES_SINCE_BACKUP} min after the backup; primary now has {before}")

    print("\n=== 2. Incident: primary dataset deleted ===")
    shutil.rmtree(primary)
    ok, problems = drlib.verify(primary, manifest)
    print(f"  integrity check: {'OK' if ok else 'FAILED'} ({len(problems)} problems, e.g. {problems[0]})")

    print("\n=== 3. Restore latest backup and verify ===")
    sw = drlib.Stopwatch()
    snap, manifest = drlib.latest_backup(vault)
    drlib.restore(snap, primary)
    ok, problems = drlib.verify(primary, manifest)
    restore_seconds = sw.seconds()
    restored = drlib.count_records(primary)
    print(f"  restored {os.path.basename(snap)} in {restore_seconds:.2f} s")
    print(f"  checksum verification: {'PASS' if ok else 'FAIL ' + str(problems)} ({len(manifest['files'])} files)")
    print(f"  records restored: {restored} of {before} (lost: {before - restored})")

    rto_minutes = DETECTION_MINUTES + DECISION_MINUTES + restore_seconds / 60
    rpo_minutes = MINUTES_SINCE_BACKUP
    rto_ok = rto_minutes <= cfg["rto_target_minutes"]
    rpo_ok = rpo_minutes <= cfg["rpo_target_minutes"]

    print("\n=== 4. Measured against targets ===")
    print(f"  RTO {rto_minutes:.1f} min (target {cfg['rto_target_minutes']}) -> {'MET' if rto_ok else 'MISSED'}")
    print(f"  RPO {rpo_minutes} min / {before - restored} records (target {cfg['rpo_target_minutes']} min) -> "
          f"{'MET' if rpo_ok else 'MISSED'}")

    report = f"""# DR drill report: {cfg['service']}

> Generated by `dr/drill.py` on {incident_at:%Y-%m-%d %H:%M} UTC. Synthetic data, local storage
> standing in for Azure Blob Storage. Detection and decision times are modelled; restore time is measured.

| Item | Result |
|---|---|
| Scenario | Accidental deletion of the primary dataset ({len(manifest['files'])} files) |
| Backup used | `{os.path.basename(snap)}` taken {MINUTES_SINCE_BACKUP} min before the incident |
| Integrity | {'All file checksums match the backup manifest' if ok else 'FAILED: ' + '; '.join(problems)} |
| Records restored | {restored} of {before} |
| Records lost (after last backup) | {before - restored} |
| **RTO** | **{rto_minutes:.1f} min** (detect {DETECTION_MINUTES} + decide {DECISION_MINUTES} + restore {restore_seconds:.2f} s) vs target {cfg['rto_target_minutes']} min: **{'MET' if rto_ok else 'MISSED'}** |
| **RPO** | **{rpo_minutes} min** vs target {cfg['rpo_target_minutes']} min: **{'MET' if rpo_ok else 'MISSED'}** |

## How the numbers were measured
- **RPO** = incident time minus the timestamp in the newest backup manifest. Records written in that gap are counted by comparing record totals before and after the restore.
- **RTO** = detection + decision + restore and verification. Restore and verification are timed by the script; detection uses the deletion alert's evaluation window; decision time is the runbook's approval step.

## Findings
1. Hourly backups meet the 60-minute RPO, but the {before - restored} orders written after the backup must be replayed from the order queue (see runbook step 6).
2. Checksum verification confirmed every restored file matches the backup manifest. Without it, a partial restore could look successful.
3. Action: move to continuous point-in-time restore (Blob PITR) to bring RPO close to zero for this container.
"""
    os.makedirs(os.path.dirname(os.path.abspath(args.report)), exist_ok=True)
    with open(args.report, "w") as fh:
        fh.write(report)
    print(f"\nWrote {os.path.relpath(args.report)}")
    success = ok and rto_ok and rpo_ok
    print("DEMO RESULT:", "PASS - data restored, checksums verified, RTO and RPO met" if success else "FAIL")
    return 0 if success else 1


if __name__ == "__main__":
    sys.exit(main())
